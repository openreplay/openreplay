export const stateById = (id: string): EmptyEntry | undefined => BY_ID.get(id);

// per language: a call site passes its title already translated
const byTitle = new Map<string, Map<string, EmptyEntry>>();
/** The first entry whose title reads `title` in `lang` (the Sessions page's
 *  posed versions share the base titles, so the first wins). */
export function stateByTitle(
  title: string,
  translate: (s: string) => string = (s) => s,
  lang = '',
): EmptyEntry | undefined {
  let titles = byTitle.get(lang);
  if (!titles) {
    titles = new Map();
    for (const e of [...EMPTY_STATES, ...SESSION_STATES]) {
      const k = translate(e.title);
      if (!titles.has(k)) titles.set(k, e);
    }
    byTitle.set(lang, titles);
  }
  return titles.get(title);
}
